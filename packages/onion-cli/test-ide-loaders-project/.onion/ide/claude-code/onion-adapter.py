#!/usr/bin/env python3
"""
Onion Adapter for Claude Code IDE
Auto-generated by @onion/cli v4.0.0-beta.1

Descobre recursos do Sistema Onion e gera claude.config.json
"""
import json
import os
from pathlib import Path
from typing import Dict, List, Optional
from datetime import datetime

try:
    import yaml
except ImportError:
    print("⚠️  Warning: PyYAML not installed. Install with: pip install pyyaml")
    yaml = None


class ClaudeOnionAdapter:
    """Adapter para descobrir e mapear recursos Onion para Claude Code"""
    
    def __init__(self, project_root: Optional[str] = None):
        """
        Inicializa o adapter
        
        Args:
            project_root: Raiz do projeto (padrão: diretório atual)
        """
        if project_root is None:
            # Tentar encontrar raiz do projeto (subir até encontrar .onion/)
            current = Path.cwd()
            while current != current.parent:
                if (current / '.onion').exists():
                    project_root = str(current)
                    break
                current = current.parent
            else:
                project_root = str(Path.cwd())
        
        self.project_root = Path(project_root)
        self.onion_root = self.project_root / '.onion'
        self.config: Optional[Dict] = None
    
    def load_config(self) -> Dict:
        """
        Carrega configuração .onion-config.yml
        
        Returns:
            Dicionário com configuração Onion
        """
        config_path = self.project_root / '.onion-config.yml'
        
        if not config_path.exists():
            print("⚠️  .onion-config.yml not found. Using default config.")
            self.config = {
                'version': '4.0.0',
                'contexts': [],
                'ides': []
            }
            return self.config
        
        if yaml is None:
            # Fallback: ler como texto e fazer parse básico
            print("⚠️  PyYAML not available. Using basic config.")
            self.config = {
                'version': '4.0.0',
                'contexts': [],
                'ides': []
            }
            return self.config
        
        with open(config_path, 'r', encoding='utf-8') as f:
            self.config = yaml.safe_load(f) or {}
        
        return self.config
    
    def discover_contexts(self) -> List[str]:
        """
        Descobre contextos disponíveis
        
        Returns:
            Lista de nomes de contextos
        """
        contexts_dir = self.onion_root / 'contexts'
        
        if not contexts_dir.exists():
            return []
        
        contexts = []
        for item in contexts_dir.iterdir():
            if item.is_dir():
                contexts.append(item.name)
        
        return sorted(contexts)
    
    def discover_commands(self, context: str) -> List[Dict]:
        """
        Descobre comandos por contexto
        
        Args:
            context: Nome do contexto
            
        Returns:
            Lista de dicionários com informações dos comandos
        """
        commands = []
        context_commands_dir = self.onion_root / 'contexts' / context / 'commands'
        
        if not context_commands_dir.exists():
            return commands
        
        # Buscar em todos os níveis
        levels = ['starter', 'intermediate', 'advanced']
        for level in levels:
            level_dir = context_commands_dir / level
            if level_dir.exists():
                for file in level_dir.iterdir():
                    if file.is_file() and file.suffix == '.md':
                        commands.append({
                            'name': file.stem,
                            'path': str(file.relative_to(self.project_root)),
                            'context': context,
                            'level': level,
                            'relative_path': str(file.relative_to(self.project_root))
                        })
        
        # Comandos na raiz do contexto (ex: help.md)
        for file in context_commands_dir.iterdir():
            if file.is_file() and file.suffix == '.md':
                # Evitar duplicatas (já adicionados dos níveis)
                if not any(cmd['name'] == file.stem and cmd['context'] == context 
                          for cmd in commands):
                    commands.append({
                        'name': file.stem,
                        'path': str(file.relative_to(self.project_root)),
                        'context': context,
                        'level': 'root',
                        'relative_path': str(file.relative_to(self.project_root))
                    })
        
        return commands
    
    def discover_agents(self, context: str) -> List[Dict]:
        """
        Descobre agentes por contexto
        
        Args:
            context: Nome do contexto
            
        Returns:
            Lista de dicionários com informações dos agentes
        """
        agents = []
        context_agents_dir = self.onion_root / 'contexts' / context / 'agents'
        
        if not context_agents_dir.exists():
            return agents
        
        for file in context_agents_dir.iterdir():
            if file.is_file() and file.suffix == '.md':
                agents.append({
                    'name': file.stem,
                    'path': str(file.relative_to(self.project_root)),
                    'context': context,
                    'relative_path': str(file.relative_to(self.project_root))
                })
        
        return agents
    
    def discover_core_commands(self) -> List[Dict]:
        """
        Descobre comandos core
        
        Returns:
            Lista de comandos core
        """
        commands = []
        core_commands_dir = self.onion_root / 'core' / 'commands'
        
        if not core_commands_dir.exists():
            return commands
        
        for file in core_commands_dir.iterdir():
            if file.is_file() and file.suffix == '.md':
                commands.append({
                    'name': file.stem,
                    'path': str(file.relative_to(self.project_root)),
                    'context': 'core',
                    'level': 'core',
                    'relative_path': str(file.relative_to(self.project_root))
                })
        
        return commands
    
    def discover_core_agents(self) -> List[Dict]:
        """
        Descobre agentes core
        
        Returns:
            Lista de agentes core
        """
        agents = []
        core_agents_dir = self.onion_root / 'core' / 'agents'
        
        if not core_agents_dir.exists():
            return agents
        
        for file in core_agents_dir.iterdir():
            if file.is_file() and file.suffix == '.md':
                agents.append({
                    'name': file.stem,
                    'path': str(file.relative_to(self.project_root)),
                    'context': 'core',
                    'relative_path': str(file.relative_to(self.project_root))
                })
        
        return agents
    
    def discover(self) -> Dict:
        """
        Descobre todos os recursos Onion
        
        Returns:
            Dicionário com todos os recursos descobertos
        """
        if self.config is None:
            self.load_config()
        
        contexts = self.discover_contexts()
        commands = []
        agents = []
        
        # Comandos e agentes core
        commands.extend(self.discover_core_commands())
        agents.extend(self.discover_core_agents())
        
        # Comandos e agentes por contexto
        for context in contexts:
            commands.extend(self.discover_commands(context))
            agents.extend(self.discover_agents(context))
        
        return {
            'config': self.config or {},
            'contexts': contexts,
            'commands': commands,
            'agents': agents
        }
    
    def generate_config(self) -> None:
        """
        Gera claude.config.json na raiz do projeto
        """
        resources = self.discover()
        config_path = self.project_root / 'claude.config.json'
        
        # Mapear comandos para formato Claude
        claude_commands = []
        for cmd in resources['commands']:
            command_name = cmd['name'] if cmd['context'] == 'core' else f"{cmd['context']}/{cmd['name']}"
            claude_commands.append({
                'name': command_name,
                'path': cmd['relative_path'],
                'context': cmd['context'],
                'level': cmd['level'],
                'description': f"Onion command: {command_name} ({cmd['level']})"
            })
        
        # Mapear agentes para formato Claude
        claude_agents = []
        for agent in resources['agents']:
            agent_name = agent['name'] if agent['context'] == 'core' else f"{agent['context']}/{agent['name']}"
            claude_agents.append({
                'name': agent_name,
                'path': agent['relative_path'],
                'context': agent['context'],
                'description': f"Onion agent: {agent_name}"
            })
        
        # Gerar config JSON
        claude_config = {
            'onion': {
                'version': '4.0.0-beta.1',
                'generated': datetime.now().isoformat(),
                'contexts': resources['contexts'],
                'commands': claude_commands,
                'agents': claude_agents
            },
            'commands': [
                {
                    'name': cmd['name'],
                    'path': cmd['path'],
                    'metadata': {
                        'context': cmd['context'],
                        'level': cmd['level'],
                        'description': cmd['description']
                    }
                }
                for cmd in claude_commands
            ],
            'agents': [
                {
                    'name': agent['name'],
                    'path': agent['path'],
                    'metadata': {
                        'context': agent['context'],
                        'description': agent['description']
                    }
                }
                for agent in claude_agents
            ]
        }
        
        with open(config_path, 'w', encoding='utf-8') as f:
            json.dump(claude_config, f, indent=2, ensure_ascii=False)
        
        print("✅ Generated claude.config.json with " + str(len(claude_commands)) + " commands and " + str(len(claude_agents)) + " agents")
    
    def generate_claude_md(self) -> None:
        """
        Gera CLAUDE.md com instruções para Claude Code
        """
        resources = self.discover()
        claude_md_path = self.project_root / 'CLAUDE.md'
        
        # Construir conteúdo Markdown
        md_lines = [
            "# Sistema Onion - Claude Code Integration",
            "",
            "Este projeto usa o **Sistema Onion v4.0** - Multi-Context Development Orchestrator.",
            "",
            "## Contextos Disponíveis",
            ""
        ]
        
        # Adicionar contextos
        for ctx in resources['contexts']:
            help_str = "help"
            backtick = chr(96)
            context_line = "- **" + ctx + "**: Use " + backtick + "/" + ctx + "/" + help_str + backtick + " para ver comandos disponíveis"
            md_lines.append(context_line)
        
        md_lines.extend([
            "",
            "## Comandos Principais",
            "",
            "### Core Commands"
        ])
        
        # Adicionar comandos core
        core_commands = [cmd for cmd in resources['commands'] if cmd['context'] == 'core' and cmd['level'] == 'core']
        for cmd in core_commands:
            desc = cmd.get('description', 'Onion command')
            cmd_name = cmd['name']
            backtick = chr(96)
            cmd_line = "- " + backtick + "/" + cmd_name + backtick + " - " + desc
            md_lines.append(cmd_line)
        
        md_lines.append("")
        md_lines.append("### Por Contexto")
        md_lines.append("")
        
        # Adicionar comandos por contexto
        for ctx in resources['contexts']:
            md_lines.append("### " + ctx.capitalize())
            starter_commands = [cmd for cmd in resources['commands'] if cmd['context'] == ctx and cmd['level'] == 'starter']
            backtick = chr(96)
            for cmd in starter_commands[:5]:  # Limitar a 5 por contexto
                cmd_name = cmd['name']
                cmd_level = cmd.get('level', 'command')
                cmd_line = "- " + backtick + "/" + ctx + "/" + cmd_name + backtick + " - " + cmd_level
                md_lines.append(cmd_line)
            md_lines.append("")
        
        md_lines.extend([
            "## Agentes Disponíveis",
            ""
        ])
        
        # Adicionar agentes (limitar a 10)
        for agent in resources['agents'][:10]:
            agent_name = agent['name']
            agent_context = agent['context']
            # Construir linha usando partes separadas para evitar problemas com @ e backticks
            prefix_part = "- "
            backtick_start = chr(96)
            at_symbol = chr(64)
            backtick_end = chr(96)
            suffix_part = " - Agente do contexto "
            agent_line = prefix_part + backtick_start + at_symbol + agent_name + backtick_end + suffix_part + agent_context
            md_lines.append(agent_line)
        
        md_lines.extend([
            "",
            "## Como Usar",
            "",
            "1. Use comandos com / seguido do contexto e nome: /contexto/comando",
            "2. Use agentes com " + chr(64) + " seguido do nome: " + chr(64) + "product-agent",
            "3. Consulte /help para ajuda global ou /contexto/help para contexto especifico",
            "",
            "## Configuração",
            "",
            "- **Config**: " + chr(96) + "claude.config.json" + chr(96) + " (gerado automaticamente)",
            "- **Onion Root**: " + chr(96) + ".onion/" + chr(96),
            "- **Versão**: 4.0.0-beta.1",
            "",
            "---",
            "",
            "**Gerado por**: " + chr(64) + "onion/cli v4.0.0-beta.1",
            "**Última atualização**: " + datetime.now().isoformat()
        ])
        
        md_content = "\n".join(md_lines)
        
        with open(claude_md_path, 'w', encoding='utf-8') as f:
            f.write(md_content)
        
        print("✅ Generated CLAUDE.md")


# Singleton instance
_adapter_instance: Optional[ClaudeOnionAdapter] = None


def get_adapter(project_root: Optional[str] = None) -> ClaudeOnionAdapter:
    """
    Obtém instância singleton do adapter
    
    Args:
        project_root: Raiz do projeto (opcional)
        
    Returns:
        Instância do ClaudeOnionAdapter
    """
    global _adapter_instance
    if _adapter_instance is None:
        _adapter_instance = ClaudeOnionAdapter(project_root)
    return _adapter_instance


# Auto-executar se chamado diretamente
if __name__ == '__main__':
    import sys
    
    project_root = sys.argv[1] if len(sys.argv) > 1 else None
    adapter = get_adapter(project_root)
    
    try:
        adapter.generate_config()
        adapter.generate_claude_md()
        print("✅ Claude adapter executed successfully")
    except Exception as e:
        print(f"❌ Error: {e}", file=sys.stderr)
        import traceback
        traceback.print_exc()
        sys.exit(1)
